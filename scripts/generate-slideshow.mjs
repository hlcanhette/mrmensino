import { readdir, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const entries = await readdir(new URL('assets/slideshow/', root), { withFileTypes: true });
const images = entries
  .filter(entry => entry.isFile() && /\.(jpe?g|png|webp|gif|avif)$/i.test(entry.name))
  .map(entry => entry.name)
  .sort((a, b) => a.localeCompare(b, 'pt-BR', { numeric: true }))
  .map(name => `assets/slideshow/${encodeURIComponent(name)}`);

await writeFile(new URL('assets/slideshow-images.js', root),
  `// Generated by scripts/generate-slideshow.mjs.\nwindow.slideshowImages = ${JSON.stringify(images, null, 2)};\n`);
console.log(`Slideshow: ${images.length} images.`);
